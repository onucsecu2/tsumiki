/**
 * Regenerate CHANGELOG.md from src/changelog.ts, which the in-app panel also
 * reads. One source, so the file and the panel can never disagree.
 *
 *   npm run changelog
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const src = readFileSync(join(root, 'src/changelog.ts'), 'utf8')
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))

// The file is data, not logic — evaluate just the array literal rather than
// pulling in a TypeScript toolchain to read it.
let body = src.slice(src.indexOf('export const RELEASES'))
// stop at the next top-level export, or lastIndexOf(']') runs into RELEASES[0]
const nextExport = body.indexOf('\nexport ', 1)
if (nextExport > 0) body = body.slice(0, nextExport)
const literal = body.slice(body.indexOf('['), body.lastIndexOf(']') + 1)
const releases = new Function(`return ${literal}`)()

const LABEL = { new: 'New', fix: 'Fixed', change: 'Changed' }
const lines = ['# Changelog', '', '<!-- generated by npm run changelog — edit src/changelog.ts -->', '']
for (const r of releases) {
  lines.push(`## v${r.version} — ${r.date}`, '', r.headline, '')
  for (const c of r.changes) lines.push(`- **${LABEL[c.kind]}** — ${c.text}`)
  lines.push('')
}
writeFileSync(join(root, 'CHANGELOG.md'), lines.join('\n'))

if (releases[0]?.version !== pkg.version) {
  console.error(`\n  ! package.json is ${pkg.version} but the newest release note is ${releases[0]?.version}.`)
  process.exit(1)
}
console.log(`CHANGELOG.md written — ${releases.length} releases, newest v${releases[0].version}`)
